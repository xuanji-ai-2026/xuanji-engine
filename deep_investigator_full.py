    def extract_git_commits_all(self):
        """提取所有Git提交"""
        try:
            result = subprocess.check_output(
                ['git', 'log', '--all', '--pretty=format:%an|%ae|%s|%H'],
                stderr=subprocess.DEVNULL,
                cwd=self.engine_path
            ).decode('utf-8')

            commits_by_emp = defaultdict(int)
            commits_by_emp_files = defaultdict(list)

            for line in result.split('\n'):
                if not line.strip():
                    continue
                parts = line.split('|')
                if len(parts) >= 4:
                    author = parts[0]
                    for emp_id in range(1, 201):
                        emp_str = f"{emp_id:03d}"
                        if emp_str in author:
                            commits_by_emp[emp_str] += 1
                            commits_by_emp_files[emp_str].append({
                                'message': parts[2],
                                'hash': parts[3]
                            })

            return commits_by_emp, commits_by_emp_files
        except Exception as e:
            print(f"❌ 提取Git提交失败: {e}")
            return {}, {}

    def parse_automation_employees(self):
        """解析自动化系统中的员工注册"""
        employees = defaultdict(dict)

        if not os.path.exists(self.automate_file):
            print(f"❌ 自动化系统文件不存在: {self.automate_file}")
            return employees

        with open(self.automate_file, 'r', encoding='utf-8') as f:
            content = f.read()

        # 提取所有星组的员工
        star_patterns = {
            'xj01': r'xj01\s*=\s*\[(.*?)\]',
            'xj02': r'xj02\s*=\s*\[(.*?)\]',
            'xj03': r'xj03\s*=\s*\[(.*?)\]',
            'xj04': r'xj04\s*=\s*\[(.*?)\]',
            'xj05': r'xj05\s*=\s*\[(.*?)\]',
            'xj06': r'xj06\s*=\s*\[(.*?)\]',
            'xj07': r'xj07\s*=\s*\[(.*?)\]',
            'xj08': r'xj08\s*=\s*\[(.*?)\]',
            'xj09': r'xj09\s*=\s*\[(.*?)\]',
            'xj10': r'xj10\s*=\s*\[(.*?)\]',
        }

        for star, pattern in star_patterns.items():
            match = re.search(pattern, content, re.DOTALL)
            if match:
                members_str = match.group(1)
                for m in re.finditer(r'\("(\d+)", "([^"]+)", "([^"]+)"', members_str):
                    emp_id = m.group(1)
                    emp_name = m.group(2)
                    employees[emp_id] = {
                        'star': star,
                        'name': emp_name,
                        'project': m.group(3)
                    }

        return employees

